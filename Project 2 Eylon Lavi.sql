WITH TBL1
AS
(SELECT I.InvoiceDate,YEAR(I.InvoiceDate) AS THEYEAR,DATEPART(Q,I.InvoiceDate) AS THEQUARTER
,C.CustomerName,IL.UnitPrice*IL.Quantity AS CUSTOMERPRICE
 FROM Sales.Invoices I JOIN Sales.Customers C
ON I.CustomerID=C.CustomerID
	JOIN Sales.InvoiceLines IL
ON I.InvoiceID=IL.InvoiceID),
TBL2 AS
(SELECT THEYEAR,THEQUARTER ,CUSTOMERNAME,
SUM(TBL1.CUSTOMERPRICE) 
AS CUSTOMERPRICE
FROM TBL1
GROUP BY THEYEAR,THEQUARTER ,TBL1.CustomerName),
TBL3 AS
(SELECT THEYEAR,THEQUARTER ,CUSTOMERNAME,
SUM(TBL2.CUSTOMERPRICE) OVER(PARTITION BY THEYEAR,THEQUARTER,CUSTOMERNAME ORDER BY CUSTOMERPRICE DESC)
AS CUSTOMERPRICE
FROM TBL2),
TBL4 AS
(SELECT THEYEAR,THEQUARTER ,CUSTOMERNAME,CUSTOMERPRICE,
RANK() OVER(PARTITION BY THEYEAR,THEQUARTER ORDER BY TBL3.CUSTOMERPRICE DESC) AS RNK
FROM TBL3)
SELECT *
FROM TBL4
WHERE RNK<=5

