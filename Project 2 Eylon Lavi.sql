WITH TBL1
AS
(SELECT YEAR(InvoiceDate) AS INVOICEYEAR,SUM(OL.UnitPrice*OL.PickedQuantity) AS INCOMEPERYEAR,
MAX(MONTH(InvoiceDate)) AS NUMBEROFDISTINCRMONTH
FROM Sales.Invoices I JOIN Sales.OrderLines OL
ON I.OrderID=OL.OrderID
GROUP BY YEAR(InvoiceDate)),
TBL2 AS
(SELECT *,ROUND((INCOMEPERYEAR/NUMBEROFDISTINCRMONTH)*12,2) AS YEARLYLINIARINCOME
FROM TBL1),
TBL3 AS
(SELECT *,(YEARLYLINIARINCOME-LAG(YEARLYLINIARINCOME)OVER(ORDER BY YEARLYLINIARINCOME))
/LAG(YEARLYLINIARINCOME)OVER(ORDER BY YEARLYLINIARINCOME)*100 AS GROWTHRATE
FROM TBL2)
SELECT INVOICEYEAR,FORMAT(INCOMEPERYEAR,'#,#.00') AS INCOMEPERYEAR,NUMBEROFDISTINCRMONTH,
FORMAT(YEARLYLINIARINCOME,'#,#.00') AS YEARLYLINIARINCOME,
FORMAT(GROWTHRATE,'#,#.00') AS GROWTHRATE
FROM TBL3











